#!/usr/bin/env python3
# src/assets.h: the font and the big digits for win-picoamp.
#
#   python3 tools/gen_assets.py > src/assets.h
#
# font:   the 8 x 8 font of C-BIOS (tools/cbios_font.bin, 256 characters, BSD
#         licence, see third_party/cbios/LICENSE), shifted one pixel right as
#         PICOAMP does with the machine's font (it is drawn for 6-pixel cells).
# digits: PICOAMP's 7-segment digits (tools/digits.inc, from gen_digits.py of
#         msx-picoplay-picoamp): 10 x 6 cells of 8 bytes, then the colon (3 cells).
import os, re
here = os.path.dirname(os.path.abspath(__file__))

font = open(os.path.join(here, 'cbios_font.bin'), 'rb').read()
assert len(font) == 2048
print('// generated by tools/gen_assets.py - do not edit')
print('#pragma once')
print('#include <stdint.h>')
print('static const uint8_t font8[256 * 8] = {')
for c in range(256):
    row = [b >> 1 for b in font[c * 8:c * 8 + 8]]
    print('    ' + ','.join('0x%02X' % v for v in row) + ',')
print('};')

vals = []
for line in open(os.path.join(here, 'digits.inc')):
    m = re.match(r'\s*db\s+(.*)', line)
    if m:
        vals += [int(v.strip().lstrip('#'), 16) for v in m.group(1).split(',')]
assert len(vals) == 10 * 48 + 24, len(vals)
print('static const uint8_t digits7[10 * 48] = {')
for i in range(0, 480, 8):
    print('    ' + ','.join('0x%02X' % v for v in vals[i:i + 8]) + ',')
print('};')
print('static const uint8_t colon7[24] = {')
for i in range(480, 504, 8):
    print('    ' + ','.join('0x%02X' % v for v in vals[i:i + 8]) + ',')
print('};')
